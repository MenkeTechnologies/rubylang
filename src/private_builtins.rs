//! Which of MRI's built-in methods are PRIVATE.
//!
//! [`crate::arity_table`] lists every built-in by defining module but does not
//! record visibility, and `respond_to?` must: `3.respond_to?(:puts)` is false
//! while `3.respond_to?(:puts, true)` is true, and `Object.new.respond_to?(:to_s)`
//! is true. Each row here is a `(owner, method)` row of that table which the
//! reference interpreter reports in `owner.private_instance_methods(false)`.
//!
//! Derived from the reference interpreter, named by ABSOLUTE PATH (bare `ruby`
//! is rubylang itself wherever it is installed):
//!
//! ```text
//! /opt/homebrew/opt/ruby/bin/ruby -e '
//!   src = File.read("src/arity_table.rs")[/BUILTIN_METHODS: .*?\n\];/m]
//!   src.scan(/\(\s*"([^"]+)",\s*"([^"]+)",\s*-?\d+,/m).select { |o, m|
//!     k = (Object.const_get(o) rescue nil)
//!     k && !o.start_with?("#<") && k.private_instance_methods(false).include?(m.to_sym)
//!   }.sort.each { |o, m| puts "    (#{o.inspect}, #{m.inspect})," }'
//! ```

