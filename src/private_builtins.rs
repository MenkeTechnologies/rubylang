/// Whether the built-in `method` defined by `owner` is private there.
pub fn is_private(owner: &str, method: &str) -> bool {
    PRIVATE_BUILTIN_METHODS
        .binary_search_by(|(o, m)| (*o, *m).cmp(&(owner, method)))
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_for_binary_search() {
        assert!(PRIVATE_BUILTIN_METHODS.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn kernel_functions_are_private_and_object_methods_are_not() {
        assert!(is_private("Kernel", "puts"));
        assert!(is_private("BasicObject", "initialize"));
        assert!(!is_private("Kernel", "freeze"));
        assert!(!is_private("Kernel", "respond_to?"));
    }
}
