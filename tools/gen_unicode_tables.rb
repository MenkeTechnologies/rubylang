# Regenerates `src/unicode_tables.rs` — the Unicode character classes rubylang
# answers String questions from, dumped out of the reference interpreter's own
# Onigmo tables so they follow MRI's Unicode version rather than whichever one
# a Rust crate happened to ship.
#
#   /opt/homebrew/opt/ruby/bin/ruby tools/gen_unicode_tables.rb > src/unicode_tables.rs \
#     && cargo fmt
#
# MUST be a real MRI, given by absolute path. Bare `ruby` is rubylang itself
# wherever rubylang is installed, and regenerating from rubylang would freeze
# rubylang's own answers as the reference it is measured against.
#
# Each class is the set of code points a POSIX bracket matches in MRI:
#
#   ALPHA  [[:alpha:]]  ONIGENC_CTYPE_ALPHA — what `String#succ` counts as a letter
#   DIGIT  [[:digit:]]  ONIGENC_CTYPE_DIGIT — what `String#succ` counts as a digit

abort "gen_unicode_tables.rb must run under MRI, not #{RUBY_ENGINE}" unless RUBY_ENGINE == "ruby"

CLASSES = {
  "ALPHA" => /\A[[:alpha:]]\z/,
  "DIGIT" => /\A[[:digit:]]\z/,
}

# The inclusive code point ranges (surrogates excluded) whose character `re`
# matches.
def ranges(re)
  out = []
  start = nil
  (0..0x10FFFF).each do |c|
    hit = !(0xD800..0xDFFF).cover?(c) && re.match?(c.chr("UTF-8"))
    if hit
      start ||= c
    elsif start
      out << [start, c - 1]
      start = nil
    end
  end
  out << [start, 0x10FFFF] if start
  out
end

puts "//! Unicode character classes, generated by `tools/gen_unicode_tables.rb`"
puts "//! from #{RUBY_DESCRIPTION.split(" (").first} (Unicode #{RbConfig::CONFIG["UNICODE_VERSION"]})."
puts "//! Do not edit by hand: regenerate."
puts
CLASSES.each do |name, re|
  rs = ranges(re)
  puts "/// The code points `#{re.source[2..-3]}` matches in MRI, as inclusive ranges."
  puts "pub const #{name}: &[(u32, u32)] = &["
  rs.each { |a, b| puts "    (0x#{a.to_s(16).upcase}, 0x#{b.to_s(16).upcase})," }
  puts "];"
  puts
end
puts <<~RUST
  fn in_table(table: &[(u32, u32)], c: u32) -> bool {
      table
          .binary_search_by(|&(lo, hi)| {
              if hi < c {
                  std::cmp::Ordering::Less
              } else if lo > c {
                  std::cmp::Ordering::Greater
              } else {
                  std::cmp::Ordering::Equal
              }
          })
          .is_ok()
  }

  /// Whether MRI's `[[:alpha:]]` matches the code point `c`.
  pub fn is_alpha(c: u32) -> bool {
      in_table(ALPHA, c)
  }

  /// Whether MRI's `[[:digit:]]` matches the code point `c`.
  pub fn is_digit(c: u32) -> bool {
      in_table(DIGIT, c)
  }
RUST
